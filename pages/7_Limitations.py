st.markdown(r"""
### 1. Sample Size Limitation (N = 100)
- **Constraint**: The study is conducted on a stratified subset of 100 QA answers (40 correct / 30 partly / 30 incorrect).
- **Impact**: While stratified sampling ensures adequate representation across hallucination tiers, $N=100$ remains a compact sample for benchmarking NLP evaluators. Statistical power for fine-grained sub-group comparisons (such as model-specific error rates across Mistral vs Llama vs GPT) is limited.

---

### 2. Wide Bootstrap Confidence Intervals
- **Constraint**: With $N=100$, 95% non-parametric bootstrap confidence intervals (1,000 resamples) for Spearman $r_s$ and Kendall $\tau_b$ span moderate intervals (typically $\pm 0.15$ to $\pm 0.25$).
- **Impact**: Point estimates should not be interpreted as absolute constants. In particular, distinguishing between moderate correlation ($r \approx 0.50$) and strong correlation ($r \approx 0.70$) requires larger cohort sizes ($N \ge 500$).

---

### 3. Model Confounding: Lack of Independence (Gemini as Evaluator and Judge)
- **Constraint**: The same underlying LLM family (Gemini 2.5 Flash) was employed as both:
  1. The decomposition engine and reverse-question generator for RAGAS.
  2. The direct LLM judge.
  3. The proxy passage relevance evaluator.
- **Impact**: The evaluation systems are **not statistically independent**. Systematic inductive biases, tokenization preferences, and knowledge priors specific to Gemini are shared across all automated metrics. When evaluating answers originally generated by GPT-4, Llama-2, or Mistral, Gemini may exhibit familial bias or blind spots that correlate with its own generation patterns.

---

### 4. Proxy Passage Relevance Marks
- **Constraint**: RAGTruth lacks passage-level human ground-truth relevance labels. To compute MRR and NDCG, this study uses a cached binary LLM judgment (Gemini evaluating whether a passage directly supports the question-answer pair).
- **Impact**: The retrieval metrics are conditioned on the LLM's own comprehension of relevance rather than human annotator labels. If the LLM misidentifies whether a passage contains supporting facts, that error propagates directly into the Reciprocal Rank and NDCG scores.

---

### 5. Single Human Relabeller (Subjective Variance)
- **Constraint**: In the blind manual relabelling phase (Page 2: Annotate), a single human annotator relabels the 35-item subset.
- **Impact**: Single-annotator evaluation cannot capture population-level human consensus or inter-annotator disagreement. Boundary cases between `correct` (completely faithful) and `partly` (minor ungrounded phrasing) involve subjective interpretation of whether a detail is an extrapolation or common-sense knowledge.

---

### 6. Ground Truth Label-Mapping Assumptions
- **Constraint**: Ground truth labels were derived from word-level hallucination span counts and types using a discrete threshold rule:
  - 0 spans -> `correct`
  - 1 subtle span OR span length $\le 80$ characters -> `partly`
  - $\ge 2$ spans OR evident span $> 80$ characters -> `incorrect`
- **Impact**: In reality, hallucination severity is a continuous spectrum rather than three discrete bins. A single 70-character hallucination that reverses a crucial medical dosage is far more severe than two 20-character stylistic filler phrases. Discretizing continuous span annotations introduces boundary quantization effects.

---

### 7. Recommendations for Production Evaluation
1. **Never Rely on a Single Metric**: Automatic metrics like RAGAS Faithfulness should always be paired with task-specific rule engines or cross-model judge ensembles.
2. **Mitigate Position Bias**: Production LLM judges must randomize or swap rubric option orderings and take ensemble votes or flag disagreements for human review.
3. **Monitor Length Correlation**: Regularly audit judge scores against response token length to detect verbosity bias drift.
4. **Calibrate with Regular Human Audits**: Maintain a rolling holdout set of human-annotated answers to continuously measure evaluator alignment before deploying automated guardrails.
""")
